"""Generates docs/protocol-vectors.txt (GADV protocol v1 test vectors).

Usage: python addon/tests/gen_protocol_vectors.py docs/protocol-vectors.txt

Reference encoder written independently of the Lua addon, straight from docs/protocol.md:
escape table, sorted keys, 228-byte bodies cut on UTF-8 boundaries.
"""
import sys

ESC = {"~": "~~", "^": "~c", "|": "~p", "\n": "~n", "\r": "~r", "\t": "~t", "\0": "~0"}
MAX_BODY = 228


def escape(s):
    return "".join(ESC.get(ch, ch) for ch in s)


def encode(op, fields):
    parts = [op]
    for k in sorted(fields, key=lambda x: x.encode("utf-8")):
        parts.append(escape(k) + "=" + escape(fields[k]))
    return "^".join(parts)


def split(encoded, d, mid):
    data = encoded.encode("utf-8")
    bodies = []
    pos = 0
    while pos < len(data):
        end = min(pos + MAX_BODY, len(data))
        if end < len(data):
            while end > pos + 1 and 0x80 <= data[end] < 0xC0:
                end -= 1
        bodies.append(data[pos:end])
        pos = end
    if not bodies:
        bodies = [b""]
    total = len(bodies)
    return [("%s%d,%d,%d:" % (d, mid, i + 1, total)).encode() + b for i, b in enumerate(bodies)]


def cesc(s):
    out = []
    for ch in s:
        out.append({"\\": "\\\\", "\n": "\\n", "\r": "\\r", "\t": "\\t", "\0": "\\0"}.get(ch, ch))
    return "".join(out)


