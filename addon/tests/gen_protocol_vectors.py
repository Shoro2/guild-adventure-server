HEADER = """# GADV protocol v1 test vectors (docs/protocol.md). Generated by
# addon/tests/gen_protocol_vectors.py, a reference encoder written from the spec and
# independent of the addon's Lua code. The addon tests (addon/tests/run_tests.lua) check the
# Lua implementation against this file; the module's tests should check the C++ one too.
#
# A vector is a block of lines; blocks are separated by blank lines; '#' lines are comments.
#   vector <name>
#   op <OPCODE>
#   field <key>=<value>   one line per field; <value> is the raw (unescaped) value written
#                         with C escapes \\\\ \\n \\r \\t \\0 and nothing else escaped
#   encoded <text>        the message-layer string, keys sorted bytewise
#   split <dir> <id>      chunk direction and message id used for the chunk lines
#   chunk <text>          the expected chunks in order (UTF-8 text, no escapes)
#
# Checks: Encode(op, fields) == encoded (or the same field set, if your encoder does not
# sort); Decode(encoded) == op + fields; Split(encoded, dir, id) == chunks; reassembling the
# chunks yields encoded again.
"""


def main(path):
    lines = [HEADER]
    for name, op, fields, (d, mid) in VECTORS:
        enc = encode(op, fields)
        lines.append("vector " + name)
        lines.append("op " + op)
        for k in sorted(fields, key=lambda x: x.encode("utf-8")):
            lines.append("field " + k + "=" + cesc(fields[k]))
        lines.append("encoded " + enc)
        lines.append("split %s %d" % (d, mid))
        for c in split(enc, d, mid):
            assert len(c) <= 240, "chunk too long"
            is_valid(c)
            lines.append("chunk " + c.decode("utf-8"))
        lines.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(l for l in lines if l is not None))


def is_valid(b):
    try:
        b.decode("utf-8")
        return True
    except UnicodeDecodeError:
        raise SystemExit("chunk is not valid UTF-8: %r" % b[:40])


if __name__ == "__main__":
    main(sys.argv[1])
