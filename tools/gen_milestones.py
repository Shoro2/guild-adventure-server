#!/usr/bin/env python3
"""Generates the world table ga_milestone_template: the tiered guild achievements (the owner, 2026-11-12).

    python -X utf8 tools/gen_milestones.py

writes modules/mod-guild-adventure/data/sql/db-world/base/ga_milestone_template.sql. Every series has its tiers with a
threshold, the guild points a tier gives and the level cap it needs ("requires_level"): tiers beyond classic content
(levels 70 and 80, skill 375 and 450) are in the table but stay inactive while the server's MaxPlayerLevel is below
it. The tier that is the highest active one of its series gives GuildAdventure.Milestones.LastTierFactor times its
points (MilestoneService, docs/guild-management.md "Tiered guild achievements").

The ids are stable (a guild's earned tiers are stored by id in ga_guild_milestone): base + subject * 10 + tier.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "modules" / "mod-guild-adventure" / "data" / "sql" / "db-world" / "base" / "ga_milestone_template.sql"

CLASSES = {1: "Warrior", 2: "Paladin", 3: "Hunter", 4: "Rogue", 5: "Priest", 6: "Death Knight", 7: "Shaman",
           8: "Mage", 9: "Warlock", 11: "Druid"}
RACES = {1: "Human", 2: "Orc", 3: "Dwarf", 4: "Night Elf", 5: "Undead", 6: "Tauren", 7: "Gnome", 8: "Troll",
         10: "Blood Elf", 11: "Draenei"}
SKILLS = {171: "Alchemy", 164: "Blacksmithing", 333: "Enchanting", 202: "Engineering", 182: "Herbalism",
          773: "Inscription", 755: "Jewelcrafting", 165: "Leatherworking", 186: "Mining", 393: "Skinning",
          197: "Tailoring", 185: "Cooking", 129: "First Aid", 356: "Fishing"}
# Creature types (CreatureType in SharedDefines.h); critters, totems, pets, gas clouds and "not specified" do not count.
CREATURE_TYPES = {1: "Beasts", 2: "Dragonkin", 3: "Demons", 4: "Elementals", 5: "Giants", 6: "Undead",
                  7: "Humanoids", 9: "Mechanicals"}

LEVELS = [(10, 0), (20, 0), (30, 0), (40, 0), (50, 0), (60, 0), (70, 70), (80, 80)]
SKILL_RANKS = [(75, 0), (150, 0), (225, 0), (300, 0), (375, 70), (450, 80)]
DECADES = [(10 ** n, 0) for n in range(2, 7)]  # 100 .. 1,000,000

# (kind, base id, subjects or None, tiers, points)
SERIES = [
    ("level_class", 10000, CLASSES, LEVELS, 5),
    ("level_race", 11000, RACES, LEVELS, 5),
    ("skill", 20000, SKILLS, SKILL_RANKS, 5),
    ("storage_items", 30000, None, DECADES, 10),
    ("guild_gold", 30100, None, DECADES, 10),            # in gold, not copper
    ("kills", 31000, CREATURE_TYPES, DECADES, 10),
    ("quests", 32000, None, [(10 ** n, 0) for n in range(1, 6)], 10),
    ("dungeons", 32100, None, [(5, 0), (25, 0), (50, 0), (100, 0), (500, 0)], 10),
    ("raids", 32200, None, [(1, 0), (5, 0), (10, 0), (25, 0), (50, 0)], 20),
]


def rows():
    for kind, base, subjects, tiers, points in SERIES:
        for subject, name in (subjects or {0: ""}).items():
            for tier, (threshold, requires_level) in enumerate(tiers, start=1):
                yield (base + subject * 10 + tier, kind, subject, tier, threshold, points, requires_level, name)


def main():
    lines = [
        "-- mod-guild-adventure: tiered guild achievements (GA_world). Applied by the worldserver's DB updater; idempotent.",
        "-- Generated by tools/gen_milestones.py: edit the script, not this file. MilestoneService,",
        "-- docs/guild-management.md \"Tiered guild achievements\".",
        "DROP TABLE IF EXISTS `ga_milestone_template`;",
        "CREATE TABLE `ga_milestone_template` (",
        "  `id` INT UNSIGNED NOT NULL,",
        "  `kind` VARCHAR(16) NOT NULL COMMENT 'level_class, level_race, skill, storage_items, guild_gold, kills, quests, dungeons, raids',",
        "  `subject` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'class, race, skill line or creature type; 0 for guild-wide series',",
        "  `tier` TINYINT UNSIGNED NOT NULL,",
        "  `threshold` BIGINT UNSIGNED NOT NULL COMMENT 'level, skill, items, gold (not copper), kills, quests or runs',",
        "  `points` INT UNSIGNED NOT NULL COMMENT 'guild points (and renown) of the tier; the last active tier of a series gets LastTierFactor times this',",
        "  `requires_level` TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'active only while MaxPlayerLevel is at least this (0 = always)',",
        "  `comment` VARCHAR(32) NOT NULL DEFAULT '',",
        "  PRIMARY KEY (`id`),",
        "  UNIQUE KEY `series_tier` (`kind`, `subject`, `tier`)",
        ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='mod-guild-adventure: tiered guild achievements';",
        "",
        "INSERT INTO `ga_milestone_template` (`id`, `kind`, `subject`, `tier`, `threshold`, `points`, `requires_level`, `comment`) VALUES",
    ]
    values = [f"({i}, '{kind}', {subject}, {tier}, {threshold}, {points}, {req}, '{name}')"
              for i, kind, subject, tier, threshold, points, req, name in rows()]
    lines.append(",\n".join(values) + ";")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(values)} rows to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
