/*
 * FightProfileStore: the guilds' fight profiles as data (docs/fight-profiles.md section 4, package FP-1).
 *
 * A fight profile belongs to a guild (its owner account), to a class and to a talent tree. It holds two rule lists:
 * the fight (list 0, played as the strategy "ga rotation") and the time between fights (list 1, the buffs, played as
 * "ga buffs"), and options: named values a condition can name ("$manaMin"), with a default in the profile and a value
 * of their own per bot (FC11). A bot has two slots, solo and group (FC3); a slot without a profile plays the default of
 * mod-playerbots. FightProfiles.h turns a stored profile into what the engine plays.
 *
 * A rule is a row of mod-playerbots' rotation (trigger -> action, as the template has it), an action of mod-playerbots
 * under conditions, a spell of the class (by the first rank of its chain: the bot casts the highest rank it knows), a
 * usable item or a trinket slot. Rules of the template that a profile does not own (movement and target housekeeping,
 * what the module's own rules cover, FC4, and in the buff list every row that is no buff, FC2) are not stored: they are
 * read from the bot's strategies when the profile is put in and emitted unchanged.
 *
 * Conditions are stored as a compact text: "[!]key[:param][op value]" joined by ";", e.g. "hp<40;!aura:1459;
 * mana>=$manaMin;enemies:10>=3". The catalogue (Conditions()) names each key with its label, group, value and parameter.
 *
 * Tables (GA_characters, ga_fight.sql): ga_fight_profile, ga_fight_profile_rule, ga_fight_profile_option,
 * ga_bot_fight_profile, ga_bot_fight_option; the templates imported from wowbot335 (GA_world, ga_fight_template.sql,
 * generated by tools/gen_fight_templates.py): ga_fight_template, ga_fight_template_rule, ga_fight_template_option.
 * World thread only.
 */

#ifndef MOD_GUILD_ADVENTURE_FIGHT_PROFILE_STORE_H
#define MOD_GUILD_ADVENTURE_FIGHT_PROFILE_STORE_H

#include "Define.h"
#include "ObjectGuid.h"
#include <array>
#include <map>
#include <string>
#include <unordered_map>
#include <vector>

namespace GuildAdventure::FightProfiles
{
    // Limits (FC7).
    constexpr uint32 MaxProfilesPerClass = 20;
    // The role a template is made for (ga_fight_template.role): a solo or damage template, or one for a group's tank
    // or healer (FightProfiles::DefaultFor).
    enum TemplateRole : uint8 { TemplateSolo = 0, TemplateTank = 1, TemplateHeal = 2 };
    constexpr uint32 MaxRulesPerProfile = 60;
    constexpr uint32 MaxConditionsPerRule = 6;
    constexpr uint32 MaxOptionsPerProfile = 12;
    constexpr std::size_t MaxProfileName = 48;
    constexpr std::size_t MaxProfileNote = 200;

    enum class ListKind : uint8
    {
        Combat = 0,
        OutOfCombat = 1
    };

    enum class ActionKind : uint8
    {
        Row = 0,      // a row of mod-playerbots: trigger (empty: a default action of the strategy) and action, by name
        Action = 1,   // an action of mod-playerbots by name, under the rule's conditions (and its trigger, if it names one)
        Spell = 2,    // a spell of the class, by the first rank of its chain
        Item = 3,     // a usable item, by its entry
        Trinket = 4   // what is worn in trinket slot 1 or 2
    };

    enum class TargetKind : uint8
    {
        Current = 0,   // the bot's current target (mod-playerbots' "current target")
        Self = 1,
        Pet = 2,
        Lowest = 3,    // the member of its group (itself included) with the least health in percent
        Tank = 4,      // the tank of its group
        Enemy = 5      // a creature of the fight that meets the rule's target conditions
    };

    enum RuleFlags : uint8
    {
        RuleOncePerTarget = 0x01,  // not again on the same target until it changes
        RuleNotTwiceInARow = 0x02  // not again right after itself
    };

    enum class CompareOp : uint8
    {
        None = 0,  // a condition without a value: it holds or does not
        Less,
        LessEqual,
        Equal,
        GreaterEqual,
        Greater
    };

    enum class ValueKind : uint8
    {
        None = 0,   // holds or does not ("in combat")
        Number,     // a count, points, yards, a level
        Percent     // 0-100
    };

    enum class ParamKind : uint8
    {
        None = 0,
        Spell,      // a spell id (any rank of its chain)
        Item,       // an item entry
        Yards,      // a distance
        Number,     // a number of its own (a health percent of "members below")
        Trigger,    // a trigger of mod-playerbots by name
        Option      // an option of the profile by its key
    };

    // One entry of the condition catalogue (the server sends it to the addon, FP-2).
    struct ConditionType
    {
        std::string key;
        char const* label;
        char const* group;   // "me", "target", "around", "pet", "group", "other"
        ValueKind value;
        ParamKind param;
        float min;
        float max;
        bool onTarget;       // evaluated on the rule's target (for the target "an enemy that meets the conditions")
    };

    struct Condition
    {
        std::string key;
        bool negate = false;
        CompareOp op = CompareOp::None;
        float value = 0.0f;
        std::string option;  // the value is this option of the profile ("$key"), the bot's own value first
        std::string param;   // spell id, item entry, yards or trigger name as text
    };

    struct Rule
    {
        ListKind list = ListKind::Combat;
        bool enabled = true;
        ActionKind kind = ActionKind::Row;
        std::string trigger;      // Row, Action: a trigger of mod-playerbots ("" for a default action of a row)
        std::string action;       // Row, Action: an action of mod-playerbots
        uint32 ref = 0;           // Spell: spell id (first rank); Item: entry; Trinket: 1 or 2
        TargetKind target = TargetKind::Current;
        uint8 flags = 0;          // RuleFlags
        uint16 minInterval = 0;   // seconds between two casts of this rule
        float relevance = 0.0f;
        uint16 node = 0;          // rows of the template from one trigger node share the number
        std::string source;       // the strategy a row of the template came from
        std::vector<Condition> conditions;
    };

    enum class OptionKind : uint8
    {
        Switch = 0,
        Number = 1,
        Percent = 2
    };

    struct Option
    {
        std::string key;
        std::string label;
        OptionKind kind = OptionKind::Number;
        float value = 0.0f;
        float min = 0.0f;
        float max = 100.0f;
    };

    struct StoredProfile
    {
        uint32 id = 0;
        uint32 owner = 0;
        uint8 classId = 0;
        uint8 tab = 0;            // the talent tree it is made for
        std::string name;
        std::string note;
        std::string templateKey;  // the strategies its template came from, e.g. "aoe,boost,cc,frost"
        uint32 revision = 1;
        std::vector<Rule> rules;  // list 0 first, then list 1, each in its order
        std::vector<Option> options;

        Option const* FindOption(std::string const& key) const;
        uint32 CountRules(ListKind list) const;
    };

    enum class Slot : uint8
    {
        Solo = 0,
        Group = 1
    };

    // The catalogue of conditions, and the text form of a list of conditions.
    std::vector<ConditionType> const& Conditions();
    ConditionType const* FindCondition(std::string const& key);
    // Parses "hp<40;!aura:1459" (false with a reason); the conditions are checked against the catalogue and the
    // profile's options.
    bool ParseConditions(std::string const& text, StoredProfile const* profile, std::vector<Condition>& out, std::string& why);
    std::string FormatConditions(std::vector<Condition> const& conditions);
    std::string DescribeCondition(Condition const& condition);
    char const* TargetName(TargetKind target);
    // The spell family of a class (a spell rule must be of it, or generic).
    uint32 ClassSpellFamily(uint8 classId);
    bool ParseTarget(std::string const& text, TargetKind& out);

    class Store
    {
    public:
        static Store& instance();

        // ga_fight_* (characters). At startup and by ".ga reload".
        void Load();

        StoredProfile const* Get(uint32 id) const;
        std::vector<StoredProfile const*> ListFor(uint32 owner, uint8 classId = 0) const;
        // The second row of templates (FP-4): read-only profiles of no guild (owner 0) from the world database,
        // the wowbot335 fight classes and the tank and healer ones of the fight class research. A bot can be given one as
        // it is (and plays the one of its tree by default, FC12); a guild copies one to edit it.
        std::vector<StoredProfile const*> Templates(uint8 classId = 0) const;
        static bool IsTemplate(StoredProfile const& profile) { return profile.owner == 0; }
        // The role a template is made for (TemplateRole), and the template of a class, talent tree and role (the lowest
        // id), 0 when there is none (FightProfiles::DefaultFor).
        uint8 RoleOf(uint32 templateId) const;
        uint32 TemplateFor(uint8 classId, uint8 tab, uint8 role) const;
        // How many templates have that role (the load line).
        uint32 CountRole(uint8 role) const;

        // Creates or replaces a profile of the owner's guild (id 0: a new one). Checks names, limits, rules and
        // conditions; false with the errors, one line per rule. Each save raises the revision.
        bool Save(StoredProfile profile, std::vector<std::string>& errors, uint32* savedId = nullptr);
        bool Delete(uint32 owner, uint32 id, std::string& why);

        // A bot's profile per slot (0: the default). Assign checks that the profile is the guild's and of the bot's class.
        uint32 Assigned(ObjectGuid bot, Slot slot) const;
        bool Assign(uint32 owner, ObjectGuid bot, uint8 classId, Slot slot, uint32 profileId, std::string& why);
        // Bots that use the profile (in either slot).
        std::vector<ObjectGuid> UsedBy(uint32 profileId) const;

        // FC11: a bot's own value of an option (false: it has none, the profile's value holds).
        bool BotOption(ObjectGuid bot, uint32 profileId, std::string const& key, float& value) const;
        bool SetBotOption(ObjectGuid bot, uint32 profileId, std::string const& key, bool reset, float value, std::string& why);
        // Every value of its own a bot has for a profile ("copy to bots" takes them along).
        std::map<std::string, float> BotOptions(ObjectGuid bot, uint32 profileId) const;
        // A counter that grows with every change of a bot's assignment or option values: the keep step puts the
        // profile in again when it changed.
        uint32 BotVersion(ObjectGuid bot) const;

        // What a validation finds wrong with a rule (empty: nothing).
        static std::string CheckRule(StoredProfile const& profile, Rule const& rule);

    private:
        Store() = default;

        uint32 LoadTemplates();
        void WriteProfile(StoredProfile const& profile);

        std::unordered_map<uint32, StoredProfile> _profiles;
        std::unordered_map<uint32, uint8> _templateRoles;
        std::unordered_map<ObjectGuid::LowType, std::array<uint32, 2>> _assigned;
        std::map<std::pair<ObjectGuid::LowType, uint32>, std::map<std::string, float>> _botOptions;
        std::unordered_map<ObjectGuid::LowType, uint32> _botVersion;
        uint32 _nextId = 1;
    };
}

#define sFightProfileStore GuildAdventure::FightProfiles::Store::instance()

#endif
